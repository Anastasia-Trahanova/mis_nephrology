-- 16. АЛЬБУМИНУРИЯ
-- Исходный основной файл не содержал готовых INSERT в albuminuria_results.
-- Поэтому здесь сохранён расчётный подход из твоего отдельного файла:
--  ACR задаётся как тестовое клиническое значение,
--  urine_albumin = ACR × urine_creatinine,
--  категория A1/A2/A3 считается автоматически.
-- =====================================================
WITH generated AS (
    SELECT
        a.id AS appointment_id,
        a.appointment_date::date AS investigation_date,
        (
            CASE a.id % 8
                WHEN 0 THEN 3.8
                WHEN 1 THEN 4.6
                WHEN 2 THEN 5.5
                WHEN 3 THEN 6.7
                WHEN 4 THEN 8.2
                WHEN 5 THEN 9.4
                WHEN 6 THEN 11.0
                ELSE 13.5
            END
        )::numeric AS urine_creatinine,
        (
            CASE
                WHEN a.id % 20 IN (0, 1, 2, 3, 4, 5, 6) THEN
                    CASE a.id % 7
                        WHEN 0 THEN 0.6
                        WHEN 1 THEN 0.9
                        WHEN 2 THEN 1.2
                        WHEN 3 THEN 1.6
                        WHEN 4 THEN 2.0
                        WHEN 5 THEN 2.4
                        ELSE 2.8
                    END
                WHEN a.id % 20 IN (7, 8, 9, 10, 11, 12, 13, 14) THEN
                    CASE a.id % 8
                        WHEN 0 THEN 3.5
                        WHEN 1 THEN 4.8
                        WHEN 2 THEN 6.2
                        WHEN 3 THEN 8.5
                        WHEN 4 THEN 11.0
                        WHEN 5 THEN 15.0
                        WHEN 6 THEN 21.0
                        ELSE 28.0
                    END
                ELSE
                    CASE a.id % 5
                        WHEN 0 THEN 35.0
                        WHEN 1 THEN 48.0
                        WHEN 2 THEN 75.0
                        WHEN 3 THEN 120.0
                        ELSE 180.0
                    END
            END
        )::numeric AS acr
    FROM appointments a
)
INSERT INTO albuminuria_results (
    appointment_id,
    investigation_date,
    urine_albumin,
    urine_albumin_unit,
    urine_creatinine,
    urine_creatinine_unit,
    albumin_creatinine_ratio,
    albuminuria_category
)
SELECT
    appointment_id,
    investigation_date,
    ROUND((acr * urine_creatinine)::numeric, 2) AS urine_albumin,
    'mg_l' AS urine_albumin_unit,
    urine_creatinine,
    'mmol_l' AS urine_creatinine_unit,
    ROUND(acr::numeric, 2) AS albumin_creatinine_ratio,
    CASE
        WHEN acr < 3 THEN 'A1'
        WHEN acr <= 30 THEN 'A2'
        ELSE 'A3'
    END AS albuminuria_category
FROM generated;

